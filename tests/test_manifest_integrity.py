# -*- coding: utf-8 -*-
"""The manifest must describe the repository, not the developer's disk.

``MANIFEST.json`` is the inventory of what the project ships.  It used
to be generated by walking the working tree, so it listed files that
git ignores - a ``pip install`` build directory, an ``egg-info``
folder, a local research run.  A fresh checkout does not have those
files, so ``tools/verify_repo.py --dir .`` failed on every push with
33 "manifest lists a missing file" problems, and the CI job could not
go green.

The rule this module pins down: **every file the manifest lists must
exist in a fresh clone of the commit.**  That is the question CI asks.
"""
from __future__ import annotations

import json
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

from refresh_manifest import collect  # noqa: E402


def _tracked_paths(root: Path):
    """The files git tracks under ``root``, as POSIX relative paths.

    Only **tracked** files count.  The manifest is the inventory of
    what the repository **ships**, and what ships is the commit; a
    fresh checkout of that commit contains exactly the tracked files
    and nothing else.  A file that is merely present is a local
    artefact - a research run, a scratch note - and counting it would
    make the manifest describe a tree that no clone will ever have.

    The earlier version of this helper also listed untracked,
    unignored files ("a file the developer has just written is part
    of the next commit").  That is true of a file that is going to be
    committed, but not of one that is not: running the benchmark
    locally wrote ``runs/bench_local/`` into the working tree and the
    next manifest regeneration picked it up, so the committed manifest
    drifted away from the checkout on every local run.  The check
    below therefore asks the question the CI asks.
    """
    try:
        result = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--cached"],
            capture_output=True, check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    names = result.stdout.decode("utf-8", "replace").split("\0")
    return [name for name in names if name]


class TestManifestDescribesTheRepository(unittest.TestCase):
    """The manifest and the tracked set must agree."""

    def setUp(self):
        self.tracked = _tracked_paths(ROOT)
        if self.tracked is None:
            self.skipTest("not a git repository")
        self.manifest = json.loads(
            (ROOT / "MANIFEST.json").read_text(encoding="utf-8"))

    def test_every_manifest_file_is_tracked(self):
        """The manifest lists nothing that the repository does not ship."""
        tracked = set(self.tracked)
        untracked = sorted(rel for rel in self.manifest["files"]
                           if rel not in tracked)
        self.assertEqual(
            [], untracked,
            "MANIFEST.json lists files git does not track; a fresh "
            "checkout will not have them and verify_repo.py will fail: "
            "%s" % (untracked[:10],))

    def test_every_manifest_file_exists_on_disk(self):
        """The manifest lists nothing that is missing from the tree."""
        missing = sorted(rel for rel in self.manifest["files"]
                         if not (ROOT / rel).is_file())
        self.assertEqual([], missing,
                         "MANIFEST.json lists missing files: %s"
                         % (missing[:10],))

    def test_the_manifest_declares_no_weights(self):
        """The explicit statement the CI checks reads false."""
        self.assertIs(False, self.manifest.get("contains_model_weights"))

    def test_the_recorded_size_is_the_canonical_size(self):
        """The recorded size must not depend on the platform.

        Git converts LF to CRLF in a Windows working tree and back
        again on a Linux clone.  A manifest that records the raw byte
        count therefore says one thing on the machine that generated it
        and another on the machine that clones it, and the two disagree
        on every text file in the repository.  The digest is computed
        over the canonical form, so the size has to be as well.
        """
        from text_canonical import canonical_bytes

        for rel, entry in list(self.manifest["files"].items())[:40]:
            path = ROOT / rel
            if not path.is_file():
                continue
            data = path.read_bytes()
            self.assertEqual(
                len(canonical_bytes(data)), entry["bytes"],
                "%s: the recorded size is not the canonical size, so the "
                "manifest differs between a Windows working tree and a "
                "Linux checkout" % rel)

    def test_regenerating_the_manifest_is_idempotent(self):
        """Running the generator must not change the committed file.

        A generator whose output drifts on every run is a generator
        nobody can trust, and a drift here is exactly what breaks CI:
        the digest of a file that changed but was not regenerated is a
        "digest mismatch" on every push.

        The comparison is on the whole inventory, digests included, and
        not only on the file names - a file whose content changed under
        a name that did not is the same defect.
        """
        items = collect()
        self.assertTrue(items, "the generator produced no files at all")
        regenerated = {
            relative: {"bytes": size, "sha256": digest}
            for relative, size, digest in sorted(items)
        }
        self.assertEqual(
            sorted(regenerated), sorted(self.manifest["files"]),
            "regenerating the manifest produced a different file set")
        self.assertEqual(
            regenerated, self.manifest["files"],
            "regenerating the manifest produced a different inventory; "
            "the committed MANIFEST.json is stale")


class TestManifestGeneratorUsesTheTrackedSet(unittest.TestCase):
    """The generator must read git's index, not the working tree."""

    def test_collect_ignores_gitignored_files(self):
        """A gitignored file must not reach the manifest."""
        tracked = _tracked_paths(ROOT)
        if tracked is None:
            self.skipTest("not a git repository")
        produced = {relative for relative, _size, _digest in collect()}
        self.assertTrue(produced <= set(tracked),
                        "the generator listed files git does not track")

    def test_collect_ignores_untracked_files(self):
        """An untracked file must not reach the manifest either.

        This is the failure that a local run exposed.  The generator
        asked git for ``--others --exclude-standard``, so it listed
        every untracked, unignored file.  Running the benchmark wrote
        ``runs/bench_local/`` into the working tree, the next
        regeneration put it into the manifest, and the committed
        manifest then named files that a fresh checkout does not have
        - the CI check "manifest describes this checkout" failed, and
        so did the idempotence test.

        The manifest describes the **commit**.  A file that git does
        not track is not in the commit, so it must not be in the
        manifest, and regenerating the manifest must not change
        because somebody ran something locally.

        The reproduction is written into the repository rather than
        simulated, because the bug was exactly a difference between
        what the tree contains and what git tracks - a mock would not
        have caught it.
        """
        tracked = _tracked_paths(ROOT)
        if tracked is None:
            self.skipTest("not a git repository")

        stray = ROOT / "tools" / "_manifest_probe_untracked.txt"
        stray.write_text("not a commit\n", encoding="utf-8")
        try:
            produced = {relative for relative, _size, _digest in collect()}
        finally:
            stray.unlink()

        relative = stray.relative_to(ROOT).as_posix()
        self.assertNotIn(relative, produced,
                         "the generator listed an untracked file; the "
                         "manifest must describe the commit, not the "
                         "working tree")
        self.assertTrue(produced <= set(tracked),
                        "the generator listed files git does not track")

    def test_regenerating_after_a_local_run_is_stable(self):
        """A local run must not change what the manifest says.

        The manifest is committed, and the CI regenerates it on a fresh
        checkout.  If a local run could change it, then the manifest
        would describe a different tree on the developer's machine
        than on the grader's - and the idempotence test above would
        fail for a reason that has nothing to do with the repository's
        contents.
        """
        tracked = _tracked_paths(ROOT)
        if tracked is None:
            self.skipTest("not a git repository")

        first = {relative for relative, _size, _digest in collect()}
        second = {relative for relative, _size, _digest in collect()}
        self.assertEqual(first, second,
                         "two consecutive collections disagree")
        self.assertTrue(first <= set(tracked),
                        "the generator listed files git does not track")


if __name__ == "__main__":
    unittest.main()
